// Compiles design/tokens.json + design/motion-tokens.json into
// src/styles/tokens.css: one block of CSS variables per mode
// ([data-mode="light|dark|night"]), the shared scale, Tailwind @theme
// mappings and one @utility per text style.
//
// Run with `npm run tokens` (also runs before dev and build).
// Never edit tokens.css by hand: change the JSON, then rerun.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));
const motion = JSON.parse(readFileSync(resolve(root, "design/motion-tokens.json"), "utf8"));
const out = resolve(root, "src/styles/tokens.css");

const MODES = ["light", "dark", "night"];
const SCHEME = { light: "light", dark: "dark", night: "dark" };

// Mobile steps from DESIGN.md §4 and §5 (below the 900px stack breakpoint).
// They live only in the token descriptions, so they're listed here once.
const MOBILE_TYPE = {
  display: "clamp(51px, 13.1vw, 192px)", // scales with width, 51 at 390
  statement: "40px",
  headline: "34px",
  email: "clamp(24px, 6.2vw, 32px)", // fluid to 24
};
// side: 16px comes from the v90 prototype (web/site-prototype).
const MOBILE_SPACE = { inset: "20px", section: "40px", divider: "96px", side: "16px" };

const v = (token) => token.$value;
const lines = [];
const push = (...l) => lines.push(...l);

// Font families: next/font sets --nf-<name>; the token stack is the fallback.
const fontFamily = (name) => {
  const stack = v(tokens.font[name]).map((f) => (/\s/.test(f) ? `"${f}"` : f));
  return `var(--nf-${name}, ${stack[0]}), ${stack.slice(1).join(", ")}`;
};
const ref = (value) => {
  const m = /^\{font\.(\w+)\}$/.exec(value);
  return m ? `var(--font-${m[1]})` : value;
};
const bezier = (b) => `cubic-bezier(${b.join(", ")})`;
const colorNames = Object.keys(tokens.color.light);

push(
  "/* Generated by scripts/build-tokens.mjs from design/*.json. Do not edit. */",
  "",
  // static: always emitted, so plain CSS can use var(--font-display) too.
  "@theme static {",
);
for (const name of Object.keys(tokens.font)) push(`  --font-${name}: ${fontFamily(name)};`);
for (const [name, t] of Object.entries(tokens.radius)) push(`  --radius-${name}: ${v(t)};`);
for (const [name, t] of Object.entries(tokens.space)) push(`  --spacing-${name}: ${v(t)};`);
for (const [name, e] of Object.entries(motion.easing)) push(`  --ease-${name}: ${e.css ?? bezier(e.bezier)};`);
for (const [name, t] of Object.entries(tokens.breakpoint)) push(`  --breakpoint-${name}: ${v(t)};`);
push("}", "");

// Values Tailwind has no namespace for.
push(":root {");
for (const [name, e] of Object.entries(motion.easing)) push(`  --dur-${name}: ${e.ms}ms;`);
push(`  --enter-rise: ${motion.easing["enter-rise"].distance};`);
for (const [name, t] of Object.entries(tokens.type)) push(`  --type-${name}-size: ${t.$value.fontSize};`);
push("}", "");

// Colour per mode. Light is also the default before the mode script runs.
for (const mode of MODES) {
  const selector = mode === "light" ? `:root, [data-mode="light"]` : `[data-mode="${mode}"]`;
  push(`${selector} {`, `  color-scheme: ${SCHEME[mode]};`);
  for (const name of colorNames) push(`  --${name}: ${v(tokens.color[mode][name])};`);
  push("}", "");
}

push(`@media (width < ${v(tokens.breakpoint.stack)}) {`, "  :root {");
for (const [name, size] of Object.entries(MOBILE_TYPE)) push(`    --type-${name}-size: ${size};`);
for (const [name, size] of Object.entries(MOBILE_SPACE)) push(`    --spacing-${name}: ${size};`);
push("  }", "}", "");

// Tailwind colours read the live mode variables: bg-canvas, text-ink, border-line…
push("@theme inline {");
for (const name of colorNames) push(`  --color-${name}: var(--${name});`);
push("}", "");

// One utility per text style: text-display, text-statement, text-label…
for (const [name, t] of Object.entries(tokens.type)) {
  const s = t.$value;
  push(`@utility text-${name} {`);
  push(`  font-family: ${ref(s.fontFamily)};`);
  push(`  font-weight: ${s.fontWeight};`);
  push(`  font-size: var(--type-${name}-size);`);
  push(`  line-height: ${s.lineHeight};`);
  if (s.letterSpacing) push(`  letter-spacing: ${s.letterSpacing};`);
  if (s.fontStyle) push(`  font-style: ${s.fontStyle};`);
  if (s.textCase === "uppercase") push(`  text-transform: uppercase;`);
  if (name === "micro") push(`  font-variant-numeric: tabular-nums;`);
  push("}", "");
}

// Keep every text style in the CSS, even when only built from a variable.
push(`@source inline("${Object.keys(tokens.type).map((n) => `text-${n}`).join(" ")}");`, "");

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`tokens → ${out.replace(root + "/", "")}`);
